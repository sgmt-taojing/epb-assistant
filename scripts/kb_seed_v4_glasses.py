def main():
    conn = sqlite3.connect(DB)
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    inserted = 0
    for e in NEW_ENTRIES:
        entry_id = "KB-EPB-" + hashlib.md5(e["title"].encode("utf-8")).hexdigest()[:10]
        exists = conn.execute(
            "SELECT 1 FROM kb_formal WHERE entry_id=?", (entry_id,)
        ).fetchone()
        if exists:
            print(f"  跳过（已存在）: {e['title']}")
            continue
        conn.execute(
            """
            INSERT INTO kb_formal
                (entry_id, module, title, content, category, src_id, trust_score, tags, summary, created_at, updated_at)
            VALUES (?,?,?,?,?,?,?,?,?,?,?)
            """,
            (
                entry_id, "epb-assistant", e["title"], e["content"], e["category"],
                "EPB-VK-MANUAL-20260831", 0.95, e["tags"],
                e["title"][:50], now, now,
            ),
        )
        inserted += 1
        print(f"  ✅ 入库: {e['title']} ({entry_id})")

    conn.commit()
    total = conn.execute("SELECT COUNT(*) FROM kb_formal").fetchone()[0]
    print(f"\n本轮新增 {inserted} 条 · KB 总计 {total} 条")
    conn.close()

if __name__ == "__main__":
    main()
