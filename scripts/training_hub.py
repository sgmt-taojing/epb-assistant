def get_all_courses():
    """聚合 training_content + EXTRA_COURSES，返回完整课程列表"""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    try:
        from training_content import TRAINING_COURSES as TC
    except Exception as e:
        print(f'[WARN] training_content 加载失败: {e}')
        TC = {}
    courses = []
    # 来自 training_content 的 4 门
    for k, v in TC.items():
        if k == 'overview':
            continue
        courses.append({
            'course_id': k,
            'title': v.get('title'),
            'duration': v.get('duration', ''),
            'level': v.get('level', '必修'),
            'icon': v.get('icon', '📘'),
            'desc': v.get('desc', ''),
            'sections': len(v.get('sections', [])),
            'quiz': len(v.get('quiz', [])),
        })
    # 新增 6 门
    for k, v in EXTRA_COURSES.items():
        courses.append({
            'course_id': k,
            'title': v.get('title'),
            'duration': v.get('duration', ''),
            'level': v.get('level', '必修'),
            'icon': v.get('icon', '📘'),
            'desc': v.get('desc', ''),
            'sections': len(v.get('sections', [])),
            'quiz': len(v.get('quiz', [])),
        })
    return courses


