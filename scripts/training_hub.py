def grade_quiz(course_id, user_answers):
    """判分 + 出证书数据"""
    detail = get_course_detail(course_id)
    if not detail or not detail.get('quiz'):
        return {'ok': False, 'error': '课程不存在或无题库'}
    quizzes = detail['quiz']
    correct = 0
    results = []
    for i, q in enumerate(quizzes):
        ua = user_answers[i] if i < len(user_answers) else -1
        is_right = (ua == q['answer'])
        if is_right:
            correct += 1
        results.append({
            'q': q['q'],
            'options': q['options'],
            'user_answer': ua,
            'correct_answer': q['answer'],
            'is_correct': is_right,
            'explanation': q.get('explanation', ''),
        })
    total = len(quizzes)
    score = round(correct / total * 100) if total else 0
    passed = score >= 60
    honor = '优秀' if score >= 85 else ('合格' if passed else '不合格')
    cert_no = ''
    if passed:
        cert_no = f"EPB-CERT-{datetime.now().strftime('%Y%m%d')}-{uuid.uuid4().hex[:8].upper()}"
    return {
        'ok': True,
        'score': score,
        'correct': correct,
        'total': total,
        'passed': passed,
        'honor': honor,
        'cert_no': cert_no,
        'results': results,
        'course_title': detail['title'],
    }


